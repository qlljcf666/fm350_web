# 2. 抽取 translate() / _() 调用
# ============================================================
def extract_strings(file_path):
    """从 Lua/HTM 文件中抽取需要翻译的字符串"""
    with open(file_path, 'r', encoding='utf-8', errors='ignore') as f:
        content = f.read()
    
    strings = []
    # 匹配 translate("...") 或 _("...") 或 _('...') 或 translate('...')
    # 处理嵌套引号
    patterns = [
        r'translate\(\s*"([^"\\]*(?:\\.[^"\\]*)*)"\s*\)',
        r'translate\(\s*\'([^\'\\]*(?:\\.[^\'\\]*)*)\'\s*\)',
        r'\b_\(\s*"([^"\\]*(?:\\.[^"\\]*)*)"\s*\)',
        r'\b_\(\s*\'([^\'\\]*(?:\\.[^\'\\]*)*)\'\s*\)',
    ]
    for pat in patterns:
        for m in re.finditer(pat, content):
            s = m.group(1)
            # 处理转义
            s = s.replace('\\"', '"').replace("\\'", "'").replace('\\\\', '\\')
            if s and len(s) > 1 and s not in strings:
                strings.append(s)
    return strings

# ============================================================
# 3. 生成 .lmo
# ============================================================
def build_lmo(strings, out_path):
    """生成 LuCI .lmo 文件"""
    header = b"nplurals=1; plural=0;\x00"
    
    with open(out_path, 'wb') as f:
        f.write(header)
        for s in strings:
            # 翻译：字典查找，找不到就用原文（LuCI 会 fallback 显示英文）
            zh = TRANSLATIONS.get(s.strip(), s.strip())
            f.write(s.encode('utf-8'))
            f.write(b'\x00')
            f.write(zh.encode('utf-8'))
            f.write(b'\x00')
    
    size = os.path.getsize(out_path)
    print(f"  ✓ {os.path.basename(out_path):40s} {len(strings):5d} strings  {size:7d} bytes")

